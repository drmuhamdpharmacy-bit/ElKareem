-- employees may edit customer details, but not VIP / archive / merge
create or replace function crm_guard_customer() returns trigger language plpgsql as $$
begin
  if auth.uid() is not null and not crm_is_staff() then
    if tg_op = 'INSERT' then
      new.is_vip := false; new.archived := false; new.merged_into := null;
    elsif new.is_vip is distinct from old.is_vip or new.archived is distinct from old.archived
       or new.merged_into is distinct from old.merged_into or new.alias_erp is distinct from old.alias_erp then
      raise exception 'not_allowed';
    end if;
  end if;
  if tg_op = 'INSERT' and new.created_by is null then new.created_by := crm_me_name(); end if;
  if new.primary_branch is not null and not (new.primary_branch = any(new.branches)) then
    new.branches := array_append(new.branches, new.primary_branch);
  end if;
  if new.primary_branch is null and cardinality(new.branches) > 0 then new.primary_branch := new.branches[1]; end if;
  return new;
end $$;
drop trigger if exists crm_customers_guard on crm_customers;
create trigger crm_customers_guard before insert or update on crm_customers for each row execute function crm_guard_customer();

-- change history, written automatically (no way to skip it from the website)
create or replace function crm_log() returns trigger language plpgsql security definer set search_path = public as $$
declare d jsonb; rid bigint;
begin
  -- row id (crm_medical has none: it is keyed by customer_id)
  rid := coalesce(to_jsonb(coalesce(new, old))->>'id', to_jsonb(coalesce(new, old))->>'customer_id')::bigint;
  if tg_op = 'DELETE' then d := to_jsonb(old);
  elsif tg_op = 'INSERT' then d := to_jsonb(new);
  else
    select jsonb_object_agg(n.key, jsonb_build_object('من', o.value, 'إلى', n.value)) into d
      from jsonb_each(to_jsonb(new)) n join jsonb_each(to_jsonb(old)) o using (key)
     where n.value is distinct from o.value and n.key not in ('updated_at','name_search','phone_norm');
    if d is null then return new; end if;
  end if;
  insert into crm_audit(user_name, emp_id, action, entity, entity_id, details)
  values (crm_me_name(), crm_me_emp(), lower(tg_op), tg_table_name, rid, d);
  return coalesce(new, old);
end $$;
do $$ declare t text; begin
  foreach t in array array['crm_customers','crm_plans','crm_followups','crm_medical','crm_protocols'] loop
    execute format('drop trigger if exists %I on %I', t || '_log', t);
    execute format('create trigger %I after insert or update or delete on %I for each row execute function crm_log()', t || '_log', t);
  end loop;
end $$;

