returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object('id', id, 'name', name, 'phone', phone, 'erp_id', erp_id,
           'reason', case when phone_norm = crm_phone(p_phone) then 'نفس رقم الهاتف' else 'نفس الاسم' end)), '[]')
  from crm_customers
  where crm_is_user() and merged_into is null and id is distinct from p_exclude
    and ((length(coalesce(crm_phone(p_phone), '')) >= 10 and phone_norm = crm_phone(p_phone)
          and phone_norm !~ '^(.)\1+$')
         or (crm_norm(p_name) <> '' and name_search = crm_norm(p_name)))
  limit 10
$$;

