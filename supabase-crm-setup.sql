do $$
declare t text;
begin
  -- direct read / add / edit: owner and supervisors only (employees use the crm_* functions)
  foreach t in array array['crm_customers','crm_medical','crm_plans','crm_followups','crm_contacts'] loop
    execute format('drop policy if exists crm_read on %I', t);
    execute format('create policy crm_read on %I for select to authenticated using (crm_is_staff())', t);
    execute format('drop policy if exists crm_add on %I', t);
    execute format('create policy crm_add on %I for insert to authenticated with check (crm_is_staff())', t);
    execute format('drop policy if exists crm_edit on %I', t);
    execute format('create policy crm_edit on %I for update to authenticated using (crm_is_staff()) with check (crm_is_staff())', t);
  end loop;
  -- delete: owner for customers, owner/senior for the rest
  execute 'drop policy if exists crm_del on crm_customers';
  execute 'create policy crm_del on crm_customers for delete to authenticated using (crm_is_owner())';
  foreach t in array array['crm_medical','crm_plans','crm_followups','crm_contacts'] loop
    execute format('drop policy if exists crm_del on %I', t);
    execute format('create policy crm_del on %I for delete to authenticated using (crm_is_staff())', t);
  end loop;
  -- protocols: everyone reads, owner/senior manage
  execute 'drop policy if exists crm_read on crm_protocols';
  execute 'create policy crm_read on crm_protocols for select to authenticated using (crm_is_user())';
  execute 'drop policy if exists crm_manage on crm_protocols';
  execute 'create policy crm_manage on crm_protocols for all to authenticated using (crm_is_staff()) with check (crm_is_staff())';
  -- change history: owner/senior read; written only by the trigger
  execute 'drop policy if exists crm_read on crm_audit';
  execute 'create policy crm_read on crm_audit for select to authenticated using (crm_is_staff())';
end $$;

revoke all on crm_protocols, crm_customers, crm_medical, crm_plans, crm_followups, crm_contacts, crm_audit from anon;
grant select, insert, update, delete on crm_protocols, crm_customers, crm_medical, crm_plans, crm_followups, crm_contacts to authenticated;
grant select on crm_audit to authenticated;

