-- Monthly follow-up score per employee — feeds the "متابعة العملاء" part of the KPI.
--   Each follow-up due in the month counts once:
--     done on time (by the due date + 1 day) = 100, done late = 60,
--     "no answer" recorded on time = 80 (late = 50), postponed with a new date = 70,
--     still open after its due date = 0 (charged to the employee it is assigned to).
--   Credit goes to whoever recorded the result. Cancelled follow-ups are ignored.
--   No follow-ups in a month -> no score (the KPI keeps its neutral default).
--   14-day rule (owner's decision): an employee who had follow-ups due to them in the last 14 days of the
--   month (or up to today) and recorded NO result at all in those 14 days gets 0 for that month.
create or replace function crm_kpi(p_from date, p_to date) returns table(
  emp_id text, year int, month0 int, due int, on_time int, late int, no_answer int, postponed int, overdue int, score int)
language sql stable security definer set search_path = public as $$
  with f as (
    select f.*, coalesce(case when f.status in ('done','no_answer') then f.done_by_emp end, f.assigned_emp) as who,
           case
             when f.status = 'done'      and (f.done_at at time zone 'Africa/Cairo')::date <= f.due_date + 1 then 100
             when f.status = 'done'      then 60
             when f.status = 'no_answer' and (f.done_at at time zone 'Africa/Cairo')::date <= f.due_date + 1 then 80
             when f.status = 'no_answer' then 50
             when f.status = 'postponed' then 70
             when f.status = 'open' and f.due_date < crm_today() then 0
           end as pts
    from crm_followups f
    where f.due_date between p_from and p_to and f.status <> 'cancelled'
  )
  , g as (
    select who, extract(year from due_date)::int as y, extract(month from due_date)::int - 1 as m0,
           count(*)::int as due,
           count(*) filter (where pts = 100)::int as on_time, count(*) filter (where pts = 60)::int as late,
           count(*) filter (where pts in (80, 50))::int as no_answer, count(*) filter (where pts = 70)::int as postponed,
           count(*) filter (where pts = 0)::int as overdue,
           round(avg(pts))::int as score
    from f
    where pts is not null and who is not null
      and (crm_is_staff() or who = crm_me_emp())
    group by 1, 2, 3
  )
  select g.who, g.y, g.m0, g.due, g.on_time, g.late, g.no_answer, g.postponed, g.overdue,
         case when exists (select 1 from crm_followups x
                            where x.assigned_emp = g.who and x.status <> 'cancelled'
                              and x.due_date between w.e - 13 and w.e)
               and not exists (select 1 from crm_followups x
                                where x.done_by_emp = g.who and x.done_at is not null
                                  and (x.done_at at time zone 'Africa/Cairo')::date between w.e - 13 and w.e)
              then 0 else g.score end
  from g
  cross join lateral (select least((make_date(g.y, g.m0 + 1, 1) + interval '1 month - 1 day')::date, crm_today()) as e) w
$$;

-- ---------------------------------------------------------------- owner tools
create or replace function crm_merge(p_keep bigint, p_drop bigint) returns void
language plpgsql security definer set search_path = public as $$
declare k crm_customers; d crm_customers;
begin
  if not crm_is_owner() then raise exception 'not_allowed'; end if;
  if p_keep = p_drop then raise exception 'same_customer'; end if;
  select * into k from crm_customers where id = p_keep for update;
  select * into d from crm_customers where id = p_drop for update;
  if k.id is null or d.id is null then raise exception 'not_found'; end if;
  update crm_plans     set customer_id = p_keep where customer_id = p_drop;
  update crm_followups set customer_id = p_keep where customer_id = p_drop;
  update crm_contacts  set customer_id = p_keep where customer_id = p_drop;
  if exists (select 1 from crm_medical where customer_id = p_drop) then
    if not exists (select 1 from crm_medical where customer_id = p_keep) then
      update crm_medical set customer_id = p_keep where customer_id = p_drop;
    else
      update crm_medical m set
        chronic_diseases    = coalesce(m.chronic_diseases, x.chronic_diseases),
        drug_allergies      = coalesce(m.drug_allergies, x.drug_allergies),
        current_medications = coalesce(m.current_medications, x.current_medications),
        treating_doctor     = coalesce(m.treating_doctor, x.treating_doctor),
        health_notes        = coalesce(m.health_notes, x.health_notes)
      from crm_medical x where m.customer_id = p_keep and x.customer_id = p_drop;
      delete from crm_medical where customer_id = p_drop;
    end if;
  end if;
  update crm_customers set
    phone = coalesce(k.phone, d.phone), whatsapp = coalesce(k.whatsapp, d.whatsapp), gender = coalesce(k.gender, d.gender),
    birth_date = coalesce(k.birth_date, d.birth_date), area = coalesce(k.area, d.area), address = coalesce(k.address, d.address),
    is_vip = k.is_vip or d.is_vip,
    branches = (select array_agg(distinct b) from unnest(k.branches || d.branches) b),
    alias_erp = (select array_agg(distinct a) from unnest(k.alias_erp || d.alias_erp || coalesce(d.erp_id, '')) a where a <> ''),
    notes = concat_ws(E'\n', k.notes, 'دُمج معه: ' || d.name || ' (' || coalesce(d.erp_id, '—') || ')', d.notes)
  where id = p_keep;
  update crm_customers set merged_into = p_keep, archived = true, archived_reason = 'مكرر — تم دمجه' where id = p_drop;
end $$;

-- Bulk import (owner). p_rows: [{erp_id, name, phone, whatsapp, gender, area, address, notes, alias_erp:[…],
-- chronic_diseases, drug_allergies, current_medications}]. Existing ERP numbers (also merged ones) are skipped.
create or replace function crm_import(p_rows jsonb, p_branch text default null) returns jsonb
language plpgsql as $$
declare r jsonb; added int := 0; skipped int := 0; cid bigint; erp text;
begin
  if not crm_is_owner() then raise exception 'not_allowed'; end if;
  for r in select * from jsonb_array_elements(p_rows) loop
    erp := nullif(trim(r->>'erp_id'), '');
    if erp is not null and exists (select 1 from crm_customers where erp_id = erp or erp = any(alias_erp)) then
      skipped := skipped + 1; continue;
    end if;
    if erp is null and exists (select 1 from crm_customers where name_search = crm_norm(r->>'name')
                                and phone_norm is not distinct from crm_phone(r->>'phone')) then
      skipped := skipped + 1; continue;
    end if;
    insert into crm_customers(erp_id, alias_erp, name, phone, whatsapp, gender, area, address, notes,
                              primary_branch, branches, created_by)
    values (erp, coalesce((select array_agg(x) from jsonb_array_elements_text(r->'alias_erp') x), '{}'),
            trim(r->>'name'), nullif(trim(r->>'phone'), ''), nullif(trim(r->>'whatsapp'), ''),
            case when r->>'gender' in ('ذكر','أنثى') then r->>'gender' end,
            nullif(trim(r->>'area'), ''), nullif(trim(r->>'address'), ''), nullif(trim(r->>'notes'), ''),
            p_branch, case when p_branch is null then '{}' else array[p_branch] end, 'استيراد Excel')
    returning id into cid;
    if coalesce(r->>'chronic_diseases', r->>'drug_allergies', r->>'current_medications') is not null then
      insert into crm_medical(customer_id, chronic_diseases, drug_allergies, current_medications, updated_by)
      values (cid, r->>'chronic_diseases', r->>'drug_allergies', r->>'current_medications', 'استيراد Excel');
    end if;
    added := added + 1;
  end loop;
  return jsonb_build_object('added', added, 'skipped', skipped);
end $$;

