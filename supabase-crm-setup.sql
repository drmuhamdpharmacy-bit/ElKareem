-- ---------------------------------------------------------------- care plans & follow-ups
-- Creates a care plan and its follow-ups:
--   chronic: one refill reminder (refill_days - 5 after start); the next one is created when it is done
--   others : one follow-up per day in the protocol (default: after 14 days)
create or replace function crm_create_plan(
  p_customer bigint, p_care_type text, p_title text, p_product text default null, p_protocol bigint default null,
  p_start date default null, p_refill_days int default null, p_branch text default null,
  p_assigned text default null, p_notes text default null, p_days int[] default null)
returns bigint language plpgsql security definer set search_path = public as $$
declare pr crm_protocols; pid bigint; d int; n int := 0; start date := coalesce(p_start, crm_today());
        refill int; days int[]; br text := coalesce(p_branch, crm_me_branch());
        who text := coalesce(p_assigned, crm_me_emp());
begin
  if not crm_is_user() then raise exception 'not_allowed'; end if;
  if not exists (select 1 from crm_customers where id = p_customer and merged_into is null and not archived) then raise exception 'not_found'; end if;
  if p_protocol is not null then select * into pr from crm_protocols where id = p_protocol; end if;
  refill := coalesce(p_refill_days, pr.refill_days, case when p_care_type = 'chronic' then 30 end);
  insert into crm_plans(customer_id, branch, care_type, protocol_id, title, product, start_date, refill_days,
                        assigned_emp, notes, created_by)
  values (p_customer, br, p_care_type, p_protocol, p_title, nullif(trim(p_product), ''), start,
          case when p_care_type = 'chronic' then refill end, who, nullif(trim(p_notes), ''), crm_me_name())
  returning id into pid;
  if p_care_type = 'chronic' then
    insert into crm_followups(plan_id, customer_id, branch, due_date, stage, kind, assigned_emp)
    values (pid, p_customer, br, start + greatest(1, refill - 5), 1, 'refill', who);
  else
    days := coalesce(nullif(p_days, '{}'), nullif(pr.fu_days, '{}'), '{14}');
    foreach d in array (select array_agg(x order by x) from unnest(days) x) loop
      n := n + 1;
      insert into crm_followups(plan_id, customer_id, branch, due_date, stage, kind, assigned_emp)
      values (pid, p_customer, br, start + d, n, 'check', who);
    end loop;
  end if;
  if br is not null then
    update crm_customers set branches = array_append(branches, br) where id = p_customer and not (br = any(branches));
  end if;
  return pid;
end $$;

-- Records the result of a follow-up call, logs the contact, and schedules what comes next.
create or replace function crm_record_result(
  p_followup bigint, p_status text, p_outcome text default null, p_notes text default null,
  p_channel text default 'اتصال', p_next date default null)
returns bigint language plpgsql security definer set search_path = public as $$
declare f crm_followups; p crm_plans; nid bigint; stamp text;
begin
  if not crm_is_user() then raise exception 'not_allowed'; end if;
  if p_status not in ('done','no_answer','postponed','cancelled') then raise exception 'bad_status'; end if;
  select * into f from crm_followups where id = p_followup for update;
  if not found then raise exception 'not_found'; end if;
  stamp := to_char(now() at time zone 'Africa/Cairo', 'DD/MM HH24:MI');
  update crm_followups set status = p_status, outcome = coalesce(nullif(p_outcome, ''), outcome),
         notes = case when coalesce(trim(p_notes), '') = '' then notes
                      else coalesce(notes || E'\n', '') || '[' || stamp || '] ' || trim(p_notes) end,
         done_by_emp = crm_me_emp(), done_by_name = crm_me_name(), done_at = now()
   where id = f.id;
  if p_status <> 'cancelled' then
    insert into crm_contacts(customer_id, followup_id, branch, channel, emp_id, emp_name, outcome, notes)
    values (f.customer_id, f.id, coalesce(crm_me_branch(), f.branch), p_channel, crm_me_emp(), crm_me_name(),
            case when p_status = 'no_answer' then coalesce(nullif(p_outcome, ''), 'لا يرد') else nullif(p_outcome, '') end,
            nullif(trim(p_notes), ''));
  end if;
  if f.plan_id is not null then select * into p from crm_plans where id = f.plan_id; end if;
  -- "no answer" always gets another try (tomorrow unless a date was chosen), so nobody drops off the list
  if p_status = 'no_answer' and p_next is null then p_next := crm_today() + 1; end if;
  if p_outcome = 'أوقف العلاج' and p.id is not null then
    update crm_plans set status = 'ended', end_reason = 'أوقف العلاج' where id = p.id;
    update crm_followups set status = 'cancelled' where plan_id = p.id and status = 'open' and id <> f.id;
    return null;
  end if;
  if p_next is not null then                                  -- explicit next call (e.g. no answer -> tomorrow)
    insert into crm_followups(plan_id, customer_id, branch, due_date, stage, kind, assigned_emp)
    values (f.plan_id, f.customer_id, f.branch, p_next,
            coalesce((select max(stage) from crm_followups where plan_id = f.plan_id), f.stage) + 1, f.kind,
            coalesce(f.assigned_emp, crm_me_emp()))
    returning id into nid;
  elsif p_status = 'done' and f.kind = 'refill' and p.status = 'active' and p.refill_days is not null then
    -- chronic refill: next reminder one supply later (counted from the planned date, so it does not drift)
    insert into crm_followups(plan_id, customer_id, branch, due_date, stage, kind, assigned_emp)
    values (p.id, f.customer_id, f.branch, greatest(f.due_date, crm_today()) + p.refill_days, f.stage + 1, 'refill',
            coalesce(p.assigned_emp, f.assigned_emp))
    returning id into nid;
  end if;
  -- a prescription / product plan ends by itself when nothing is left to follow
  if p.id is not null and p.care_type <> 'chronic' and nid is null
     and not exists (select 1 from crm_followups where plan_id = p.id and status in ('open','postponed')) then
    update crm_plans set status = 'ended', end_reason = 'اكتملت المتابعات' where id = p.id and status = 'active';
  end if;
  return nid;
end $$;

create or replace function crm_reschedule(p_followup bigint, p_date date, p_reason text default null)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not crm_is_user() then raise exception 'not_allowed'; end if;
  if p_date < crm_today() then raise exception 'date_in_past'; end if;
  if not exists (select 1 from crm_followups where id = p_followup and status in ('open','postponed')) then raise exception 'not_found'; end if;
  update crm_followups set due_date = p_date, status = 'postponed',
         notes = coalesce(notes || E'\n', '') || '[' || to_char(now() at time zone 'Africa/Cairo', 'DD/MM') || '] تأجيل إلى '
                 || to_char(p_date, 'DD/MM/YYYY') || coalesce(' — ' || nullif(trim(p_reason), ''), '')
   where id = p_followup;
end $$;

-- single follow-up not tied to a plan (e.g. "call back on Sunday")
create or replace function crm_add_followup(p_customer bigint, p_date date, p_notes text default null,
                                            p_branch text default null, p_assigned text default null)
returns bigint language plpgsql security definer set search_path = public as $$
declare fid bigint;
begin
  if not crm_is_user() then raise exception 'not_allowed'; end if;
  if not exists (select 1 from crm_customers where id = p_customer and merged_into is null) then raise exception 'not_found'; end if;
  insert into crm_followups(customer_id, branch, due_date, notes, assigned_emp)
  values (p_customer, coalesce(p_branch, crm_me_branch()), p_date, nullif(trim(p_notes), ''), coalesce(p_assigned, crm_me_emp()))
  returning id into fid;
  return fid;
end $$;

-- ---------------------------------------------------------------- lists (one call per screen)
create or replace function crm_customer_list(p_q text default '', p_branch text default null,
                                             p_filter text default null, p_limit int default 300)
returns jsonb language sql stable security definer set search_path = public as $$
  with base as (
    select c.*,
      (select count(*) from crm_followups f where f.customer_id = c.id and f.status in ('open','postponed')) as open_fu,
      (select count(*) from crm_followups f where f.customer_id = c.id and f.status in ('open','postponed') and f.due_date < crm_today()) as overdue_fu,
      (select min(due_date) from crm_followups f where f.customer_id = c.id and f.status in ('open','postponed')) as next_due,
      (select array_agg(distinct p.care_type) from crm_plans p where p.customer_id = c.id and p.status = 'active') as care_types,
      (select max(at) from crm_contacts k where k.customer_id = c.id) as last_contact
    from crm_customers c
    where c.merged_into is null
      and (case when p_filter = 'archived' then c.archived else not c.archived end)
      and (coalesce(p_filter, '') <> 'archived' or crm_is_staff())
      and (p_branch is null or p_branch = any(c.branches))
      -- employees: without a search word only their branch's customers who have follow-ups open
      and (crm_is_staff() or coalesce(trim(p_q), '') <> ''
           or (crm_me_branch() = any(c.branches)
               and exists (select 1 from crm_followups f where f.customer_id = c.id and f.status in ('open','postponed'))))
      and (coalesce(trim(p_q), '') = '' or (
            select bool_and(c.name_search like '%' || crm_norm(tok) || '%'
                            or (tok ~ '^[0-9٠-٩]+$' and (c.phone_norm like '%' || coalesce(crm_phone(tok), tok) || '%'
                                or c.erp_id like translate(tok, '٠١٢٣٤٥٦٧٨٩', '0123456789') || '%'
                                or translate(tok, '٠١٢٣٤٥٦٧٨٩', '0123456789') = any(c.alias_erp))))
            from regexp_split_to_table(trim(p_q), '\s+') tok))
      and crm_is_user()
  )
  select coalesce(jsonb_agg(to_jsonb(b) - 'name_search' order by
           (b.overdue_fu > 0) desc, b.next_due nulls last, b.name), '[]'::jsonb)
  from (select * from base
        where p_filter is null or p_filter = 'archived'
           or (p_filter = 'vip' and is_vip)
           or (p_filter = 'overdue' and overdue_fu > 0)
           or (p_filter = 'no_plan' and care_types is null)
           or (p_filter in ('chronic','prescription','personal_care','other') and p_filter = any(care_types))
        order by (overdue_fu > 0) desc, next_due nulls last, name
        limit greatest(1, least(p_limit, case when crm_is_staff() then 2000 else 30 end))) b   -- employees: max 30 per search
$$;

create or replace function crm_followup_list(p_scope text default 'now', p_branch text default null,
                                             p_emp text default null, p_q text default '', p_type text default null)
returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(r order by r.sort_key, r.due_date, r.id), '[]'::jsonb) from (
    select f.id, f.plan_id, f.customer_id, f.branch, f.due_date, f.stage, f.kind, f.status, f.outcome, f.notes,
           f.assigned_emp, f.done_by_name, f.done_at,
           (crm_today() - f.due_date) as days_late,
           c.name as customer_name, c.erp_id, c.phone, c.whatsapp, c.is_vip,
           p.title, p.product, p.care_type, pr.instructions,
           (select drug_allergies from crm_medical m where m.customer_id = c.id) as allergies,
           case when p_scope = 'closed' then -extract(epoch from f.done_at) else 0 end as sort_key
      from crm_followups f
      join crm_customers c on c.id = f.customer_id
      left join crm_plans p on p.id = f.plan_id
      left join crm_protocols pr on pr.id = p.protocol_id
     where crm_is_user() and c.merged_into is null and not c.archived
       and case when crm_is_staff() then (p_branch is null or f.branch = p_branch)
                else f.branch is not distinct from crm_me_branch() end          -- employees: own branch only
       and (p_emp is null or f.assigned_emp = p_emp)
       and (p_type is null or p.care_type = p_type)
       and (coalesce(trim(p_q), '') = '' or c.name_search like '%' || crm_norm(p_q) || '%'
            or c.phone_norm like '%' || coalesce(crm_phone(p_q), p_q) || '%')
       and case p_scope
             when 'now'      then f.status in ('open','postponed') and f.due_date <= crm_today() + 3
             when 'overdue'  then f.status in ('open','postponed') and f.due_date < crm_today()
             when 'today'    then f.status in ('open','postponed') and f.due_date = crm_today()
             when 'upcoming' then f.status in ('open','postponed') and f.due_date > crm_today()
             when 'closed'   then f.status in ('done','no_answer','cancelled') and f.done_at > now() - interval '60 days'
             else f.status in ('open','postponed') end
     limit 1000) r
$$;

create or replace function crm_customer_detail(p_id bigint) returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'customer', (select to_jsonb(c) - 'name_search' from crm_customers c where c.id = p_id),
    'medical',  (select to_jsonb(m) from crm_medical m where m.customer_id = p_id),
    'plans',    (select coalesce(jsonb_agg(to_jsonb(p) order by p.status = 'active' desc, p.start_date desc), '[]')
                   from crm_plans p where p.customer_id = p_id),
    'followups',(select coalesce(jsonb_agg(jsonb_build_object('id', f.id, 'plan_id', f.plan_id, 'due_date', f.due_date,
                   'stage', f.stage, 'kind', f.kind, 'status', f.status, 'outcome', f.outcome, 'notes', f.notes,
                   'assigned_emp', f.assigned_emp, 'done_by_name', f.done_by_name, 'done_at', f.done_at,
                   'branch', f.branch, 'title', p.title, 'days_late', crm_today() - f.due_date)
                   order by f.status in ('open','postponed') desc, f.due_date desc), '[]')
                   from crm_followups f left join crm_plans p on p.id = f.plan_id where f.customer_id = p_id),
    'contacts', (select coalesce(jsonb_agg(to_jsonb(k) order by k.at desc), '[]') from crm_contacts k where k.customer_id = p_id),
    'history',  (select coalesce(jsonb_agg(to_jsonb(a) order by a.at desc), '[]') from (
                   select * from crm_audit a where crm_is_staff() and (
                     (a.entity in ('crm_customers','crm_medical') and a.entity_id = p_id)
                     or (a.entity in ('crm_plans','crm_followups') and a.entity_id in (
                         select id from crm_plans where customer_id = p_id union select id from crm_followups where customer_id = p_id)))
                   order by a.at desc limit 200) a)
  ) where crm_is_user()
$$;

