-- ---------------------------------------------------------------- helpers
create or replace function crm_norm(t text) returns text
language sql immutable as $$
  select lower(regexp_replace(translate(regexp_replace(coalesce(t, ''),
         '[ؐ-ًؚ-ٰٟۖ-ۭـ]', '', 'g'),
         'أإآٱةىؤئ٠١٢٣٤٥٦٧٨٩', 'ااااهيوي0123456789'), '\s+', '', 'g'))
$$;

-- Egyptian phone -> canonical digits (restores the leading 0 Excel drops, strips +20)
create or replace function crm_phone(t text) returns text
language plpgsql immutable as $$
declare d text := regexp_replace(translate(coalesce(t, ''), '٠١٢٣٤٥٦٧٨٩', '0123456789'), '\D', '', 'g');
begin
  if d like '0020%' then d := '0' || substr(d, 5);
  elsif d like '20%' and length(d) = 12 then d := '0' || substr(d, 3);
  end if;
  if length(d) = 10 and d ~ '^1[0125]' then d := '0' || d; end if;
  return nullif(d, '');
end $$;

create or replace function crm_today() returns date
language sql stable as $$ select (now() at time zone 'Africa/Cairo')::date $$;

-- the signed-in user (from the existing profiles table)
create or replace function crm_me_role() returns text
language sql stable security definer set search_path = public as $$
  select role from profiles where id = auth.uid() $$;
create or replace function crm_me_emp() returns text
language sql stable security definer set search_path = public as $$
  select emp_id from profiles where id = auth.uid() $$;
create or replace function crm_me_name() returns text
language sql stable security definer set search_path = public as $$
  select name from profiles where id = auth.uid() $$;
create or replace function crm_me_branch() returns text
language sql stable security definer set search_path = public as $$
  select branch from profiles where id = auth.uid() $$;
create or replace function crm_is_user() returns boolean
language sql stable as $$ select coalesce(crm_me_role() in ('owner','senior','employee'), false) $$;
create or replace function crm_is_staff() returns boolean
language sql stable as $$ select coalesce(crm_me_role() in ('owner','senior'), false) $$;
create or replace function crm_is_owner() returns boolean
language sql stable as $$ select coalesce(crm_me_role() = 'owner', false) $$;

-- ---------------------------------------------------------------- tables
create table if not exists crm_protocols (
  id            bigint generated by default as identity primary key,
  name          text not null unique,
  care_type     text not null check (care_type in ('chronic','prescription','personal_care','other')),
  refill_days   int,                 -- chronic: days a supply lasts (reminder 5 days before it runs out)
  fu_days       int[] not null default '{}',   -- other types: follow-up days after the start date
  instructions  text,
  active        boolean not null default true,
  sort          int not null default 0
);

create table if not exists crm_customers (
  id               bigint generated by default as identity primary key,
  erp_id           text unique,                    -- customer number from the ERP (keeps leading zeros)
  alias_erp        text[] not null default '{}',   -- ERP numbers of merged duplicate records
  name             text not null check (length(trim(name)) >= 2),
  name_search      text generated always as (crm_norm(name)) stored,
  phone            text,
  phone_norm       text generated always as (crm_phone(phone)) stored,
  whatsapp         text,
  gender           text check (gender in ('ذكر','أنثى')),
  birth_date       date,
  area             text,
  address          text,
  notes            text,
  is_vip           boolean not null default false,
  vip_note         text,
  primary_branch   text,
  branches         text[] not null default '{}',   -- branches the customer deals with (one shared profile)
  archived         boolean not null default false,
  archived_reason  text,
  merged_into      bigint references crm_customers(id),
  created_by       text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index if not exists crm_customers_name_idx   on crm_customers (name_search);
create index if not exists crm_customers_phone_idx  on crm_customers (phone_norm);
create index if not exists crm_customers_branch_idx on crm_customers using gin (branches);

create table if not exists crm_medical (
  customer_id          bigint primary key references crm_customers(id) on delete cascade,
  chronic_diseases     text,
  drug_allergies       text,
  current_medications  text,
  treating_doctor      text,
  health_notes         text,
  updated_by           text,
  updated_at           timestamptz not null default now()
);

create table if not exists crm_plans (            -- what we follow up: a chronic disease, a prescription, a product
  id            bigint generated by default as identity primary key,
  customer_id   bigint not null references crm_customers(id) on delete cascade,
  branch        text,
  care_type     text not null check (care_type in ('chronic','prescription','personal_care','other')),
  protocol_id   bigint references crm_protocols(id),
  title         text not null,                    -- disease / prescription / product category
  product       text,                             -- medicine or product name
  start_date    date not null default crm_today(),
  refill_days   int,
  status        text not null default 'active' check (status in ('active','paused','ended')),
  end_reason    text,
  assigned_emp  text,                             -- employee code (EK…) responsible for the follow-ups
  notes         text,
  created_by    text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists crm_plans_customer_idx on crm_plans (customer_id);

create table if not exists crm_followups (
  id            bigint generated by default as identity primary key,
  plan_id       bigint references crm_plans(id) on delete cascade,
  customer_id   bigint not null references crm_customers(id) on delete cascade,
  branch        text,
  due_date      date not null,
  stage         int not null default 1,
  kind          text not null default 'check' check (kind in ('check','refill')),
  status        text not null default 'open' check (status in ('open','done','no_answer','postponed','cancelled')),
  outcome       text,
  notes         text,
  assigned_emp  text,
  done_by_emp   text,
  done_by_name  text,
  done_at       timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists crm_followups_due_idx      on crm_followups (status, due_date);
create index if not exists crm_followups_customer_idx on crm_followups (customer_id);

create table if not exists crm_contacts (          -- every call / WhatsApp / visit
  id           bigint generated by default as identity primary key,
  customer_id  bigint not null references crm_customers(id) on delete cascade,
  followup_id  bigint references crm_followups(id) on delete set null,
  branch       text,
  at           timestamptz not null default now(),
  channel      text,
  emp_id       text,
  emp_name     text,
  outcome      text,
  notes        text
);
create index if not exists crm_contacts_customer_idx on crm_contacts (customer_id);

create table if not exists crm_audit (
  id         bigint generated by default as identity primary key,
  at         timestamptz not null default now(),
  user_name  text,
  emp_id     text,
  action     text not null,
  entity     text not null,
  entity_id  bigint,
  details    jsonb
);
create index if not exists crm_audit_entity_idx on crm_audit (entity, entity_id);

