-- ---------------------------------------------------------------- helpers (internal)
create or replace function public._cairo_now() returns timestamp language sql stable as
$$ select (now() at time zone 'Africa/Cairo') $$;

-- quiet hours: 22:00–09:00 Cairo → wait until 09:00 (the check-in reminder is never held)
create or replace function public._notif_send_after(p_kind text) returns timestamptz language sql stable as $$
  select case
    when p_kind = 'checkin' then now()
    when extract(hour from public._cairo_now()) >= 22
      then ((public._cairo_now()::date + 1) + time '09:00') at time zone 'Africa/Cairo'
    when extract(hour from public._cairo_now()) < 9
      then (public._cairo_now()::date + time '09:00') at time zone 'Africa/Cairo'
    else now() end $$;

create or replace function public._notify_user(p_user uuid, p_emp text, p_branch text, p_kind text,
                                               p_title text, p_body text, p_url text, p_ref text)
 returns void language sql security definer set search_path to 'public' as $$
  insert into public.notifications (user_id, emp_id, branch, kind, title, body, url, ref, send_after)
  values (p_user, p_emp, p_branch, p_kind, left(p_title, 120), left(p_body, 600), p_url, p_ref, public._notif_send_after(p_kind))
  on conflict (user_id, ref) where ref is not null do nothing $$;

-- every login account of an employee code
create or replace function public._notify_emp(p_emp text, p_branch text, p_kind text,
                                              p_title text, p_body text, p_url text, p_ref text)
 returns void language sql security definer set search_path to 'public' as $$
  select public._notify_user(p.id, p_emp, p_branch, p_kind, p_title, p_body, p_url, p_ref)
    from public.profiles p where p.emp_id = p_emp and p.role in ('employee', 'senior') $$;

-- the supervisors of a branch + every owner (owners get a copy of everything the supervisors get)
create or replace function public._notify_staff(p_branch text, p_kind text, p_title text, p_body text, p_url text, p_ref text)
 returns void language plpgsql security definer set search_path to 'public' as $$
declare v_bname text := coalesce((select b ->> 'name' from public.app_store s, jsonb_array_elements(s.data) b
                                   where s.id = 'branches' and jsonb_typeof(s.data) = 'array' and b ->> 'id' = p_branch), p_branch);
begin
  perform public._notify_user(p.id, p.emp_id, p_branch, p_kind, p_title, p_body, p_url, p_ref)
     from public.profiles p where p.role = 'senior' and p.branch = p_branch;
  -- owners: the branch name in front, since they see all branches
  perform public._notify_user(p.id, null, p_branch, p_kind, p_title, '🏢 ' || v_bname || ' — ' || p_body, p_url, p_ref)
     from public.profiles p where p.role = 'owner';
end $$;

create or replace function public._emp_active_in(p_branch text, p_emp text) returns boolean language sql stable
 security definer set search_path to 'public' as $$
  select exists (select 1 from public.app_store s, jsonb_array_elements(s.data) e
                  where s.id = p_branch || '/employees' and jsonb_typeof(s.data) = 'array'
                    and e ->> 'id' = p_emp and coalesce(e ->> 'leftMk', '') = '') $$;

-- ---------------------------------------------------------------- called by the app
-- owner / supervisor → one employee (task, score, bonus, penalty, badge, purchase, payslip)
create or replace function public.notify_emp(p_emp text, p_branch text, p_kind text, p_title text, p_body text,
                                             p_url text default null, p_ref text default null)
 returns void language plpgsql security definer set search_path to 'public' as $$
declare v_role text; v_branch text;
begin
  select role, branch into v_role, v_branch from public.profiles where id = auth.uid();
  if not (v_role = 'owner' or (v_role = 'senior' and v_branch = p_branch)) then raise exception 'not_allowed'; end if;
  if p_kind not in ('task', 'task_score', 'bonus', 'penalty', 'badge', 'withdrawal', 'payslip', 'message') then raise exception 'bad_kind'; end if;
  if not public._emp_active_in(p_branch, p_emp) then raise exception 'not_found'; end if;
  perform public._notify_emp(p_emp, p_branch, p_kind, p_title, p_body, p_url, p_ref);
end $$;

-- the phone / browser of the signed-in user
create or replace function public.push_subscribe(p_endpoint text, p_p256dh text, p_auth text, p_ua text default null)
 returns void language plpgsql security definer set search_path to 'public' as $$
begin
  if auth.uid() is null then raise exception 'not_allowed'; end if;
  if p_endpoint !~ '^https://' then raise exception 'bad_endpoint'; end if;
  insert into public.push_subscriptions (user_id, endpoint, p256dh, auth, ua) values (auth.uid(), p_endpoint, p_p256dh, p_auth, left(p_ua, 200))
  on conflict (endpoint) do update set user_id = excluded.user_id, p256dh = excluded.p256dh, auth = excluded.auth, ua = excluded.ua;
end $$;

create or replace function public.push_unsubscribe(p_endpoint text) returns void language sql security definer set search_path to 'public' as
$$ delete from public.push_subscriptions where endpoint = p_endpoint and user_id = auth.uid() $$;

create or replace function public.push_public_key() returns text language sql stable security definer set search_path to 'public' as
$$ select v from public.notif_private where k = 'vapid_public' $$;

create or replace function public.notif_mark_read(p_id bigint default null) returns void language sql security definer set search_path to 'public' as
$$ update public.notifications set read_at = now() where user_id = auth.uid() and read_at is null and (p_id is null or id = p_id) $$;

-- ---------------------------------------------------------------- leave / late-permission requests
create or replace function public._notif_leave() returns trigger language plpgsql security definer set search_path to 'public' as $$
declare v_what text;
begin
  v_what := case when new.kind = 'إذن تأخير' then 'إذن تأخير يوم ' || to_char(new.from_date, 'DD/MM')
                 else coalesce(new.kind, 'إجازة') || ' من ' || to_char(new.from_date, 'DD/MM') || ' إلى ' || to_char(new.to_date, 'DD/MM') end;
  if tg_op = 'INSERT' and new.status = 'pending' then
    perform public._notify_staff(new.branch, 'leave_request', '🌴 طلب جديد ينتظر قرارك',
      coalesce(new.emp_name, new.emp_id) || ' — ' || v_what, '?p=leaves', 'leave:' || new.id);
  elsif tg_op = 'UPDATE' and old.status = 'pending' and new.status = 'approved' then
    perform public._notify_emp(new.emp_id, new.branch, 'leave_decision', '✅ تمت الموافقة على طلبك', v_what, '?p=myleaves', 'leave:' || new.id || ':decision');
  elsif tg_op = 'UPDATE' and old.status = 'pending' and new.status = 'rejected' then
    perform public._notify_emp(new.emp_id, new.branch, 'leave_decision', '❌ تم رفض طلبك', v_what, '?p=myleaves', 'leave:' || new.id || ':decision');
    -- the reason is saved a moment later: give it a minute before sending
    update public.notifications set send_after = greatest(send_after, now() + interval '1 minute')
     where ref = 'leave:' || new.id || ':decision' and push_sent_at is null;
  elsif tg_op = 'UPDATE' and new.status = 'rejected' and new.decision_note is distinct from old.decision_note and new.decision_note is not null then
    update public.notifications set body = v_what || ' — السبب: ' || new.decision_note
     where ref = 'leave:' || new.id || ':decision' and push_sent_at is null;
  end if;
  return new;
end $$;
drop trigger if exists notif_leave on public.leave_requests;
create trigger notif_leave after insert or update on public.leave_requests for each row execute function public._notif_leave();

-- ---------------------------------------------------------------- scheduled (every minute, see the end)
create or replace function public._notif_checkin_nudges() returns void language plpgsql security definer set search_path to 'public' as $$
declare r record; v_msgs text[] := array[
  'أنت تؤدي عملاً رائعاً — استمر 💪',
  'كل عميل تخدمه اليوم يفرق معه — شكراً لمجهودك 🌟',
  'نصف الوردية مرّ — شوية تركيز وتخلص يومك بنجاح 👏',
  'ابتسامتك جزء من العلاج — يوم موفق 😊',
  'شكراً لالتزامك — فريق الكريم فخور بك 💚'];
begin
  for r in
    select c.id, c.emp_id, c.branch from public.checkins c
     where c.kind = 'in' and c.at between now() - interval '4 hours 30 minutes' and now() - interval '4 hours'
       and not exists (select 1 from public.checkins x where x.emp_id = c.emp_id and x.at > c.at)
  loop
    perform public._notify_emp(r.emp_id, r.branch, 'checkin', v_msgs[1 + (r.id % array_length(v_msgs, 1))::int],
      'ولا تنسَ تسجيل الانصراف بمسح الكود عند خروجك 📱', '?p=mycheckin', 'nudge:' || r.id);
  end loop;
end $$;

create or replace function public._notif_daily() returns void language plpgsql security definer set search_path to 'public' as $$
declare
  v_today date := public._cairo_now()::date;
  v_sat   date := v_today - ((extract(dow from v_today)::int + 1) % 7);   -- this week's Saturday
  r record;
  v_mk text;
begin
  -- 1) customer follow-ups: today + late, one message per employee
  for r in
    select f.assigned_emp emp, min(p.branch) branch,
           count(*) filter (where f.due_date = v_today) today, count(*) filter (where f.due_date < v_today) late
      from public.crm_followups f join public.profiles p on p.emp_id = f.assigned_emp
     where f.status = 'open' and f.due_date <= v_today and f.assigned_emp is not null
     group by 1
  loop
    perform public._notify_emp(r.emp, r.branch, 'crm_digest', '📞 متابعات العملاء اليوم',
      case when r.today > 0 and r.late > 0 then 'لديك ' || r.today || ' متابعة اليوم و ' || r.late || ' متأخرة ⚠️'
           when r.today > 0 then 'لديك ' || r.today || ' متابعة اليوم'
           else 'لديك ' || r.late || ' متابعة متأخرة ⚠️' end || ' — افتح «متابعات العملاء»',
      '?p=crm_followups', 'crm:' || v_today);
  end loop;

  -- 2) 5 days without recording any follow-up (while follow-ups were due): employee + supervisors
  for r in
    select f.assigned_emp emp, min(p.branch) branch, min(p.name) name
      from public.crm_followups f join public.profiles p on p.emp_id = f.assigned_emp
     where f.status <> 'cancelled' and f.due_date between v_today - 5 and v_today
     group by 1
    having not exists (select 1 from public.crm_followups x where x.done_by_emp = f.assigned_emp
                        and (x.done_at at time zone 'Africa/Cairo')::date > v_today - 5)
       and not exists (select 1 from public.notifications n where n.emp_id = f.assigned_emp and n.kind = 'crm_idle'
                        and n.created_at > now() - interval '5 days')
  loop
    perform public._notify_emp(r.emp, r.branch, 'crm_idle', '⚠️ 5 أيام بدون متابعات',
      'لم تسجّل أي متابعة عملاء منذ 5 أيام — بعد 14 يوماً يصبح جزء المتابعة في KPI صفراً', '?p=crm_followups', 'crm_idle:' || v_today);
    perform public._notify_staff(r.branch, 'crm_idle', '⚠️ موظف بدون متابعات 5 أيام',
      coalesce(r.name, r.emp) || ' لم يسجّل أي متابعة عملاء منذ 5 أيام', '?p=crm_dashboard', 'crm_idle:' || r.emp || ':' || v_today);
  end loop;

  -- 3) Saturday: who has no task this week (Saturday → Friday) — to the supervisors
  if v_today = v_sat then
    for r in
      select b.id branch, string_agg(e ->> 'name', '، ' order by e ->> 'name') names, count(*) n
        from public.app_store br, jsonb_array_elements(br.data) bx(b0), lateral (select b0 ->> 'id' as id) b,
             public.app_store se, jsonb_array_elements(se.data) e
       where br.id = 'branches' and jsonb_typeof(br.data) = 'array'
         and se.id = b.id || '/employees' and jsonb_typeof(se.data) = 'array'
         and coalesce(e ->> 'leftMk', '') = '' and coalesce(e ->> 'movedTo', '') = ''
         and not exists (
           select 1 from public.app_store sm, jsonb_each(case when jsonb_typeof(sm.data) = 'object' then sm.data else '{}'::jsonb end) mo,
                         jsonb_array_elements(case when jsonb_typeof(mo.value) = 'array' then mo.value else '[]'::jsonb end) m
            where sm.id = b.id || '/missions' and m ->> 'empId' = e ->> 'id'
              and coalesce(m ->> 'start', '') <> '' and (m ->> 'start')::date <= v_sat + 6 and (m ->> 'due')::date >= v_sat)
       group by b.id
    loop
      perform public._notify_staff(r.branch, 'task_reminder', '🎯 مهام هذا الأسبوع',
        r.n || ' موظف بدون مهام هذا الأسبوع: ' || r.names, '?p=missions', 'tasks:' || r.branch || ':' || v_sat);
    end loop;

    -- 4) Saturday: big KPI / ranking change since last week (from the leaderboard the app saves)
    v_mk := extract(year from v_today + 6)::int || '-' || (extract(month from v_today + 6)::int - 1);   -- pay month: 26th → next month
    if extract(day from v_today) < 26 then v_mk := extract(year from v_today)::int || '-' || (extract(month from v_today)::int - 1); end if;
    for r in
      with cur as (
        select v.branch, x ->> 'id' emp, (x ->> 'kpi')::int kpi,
               rank() over (partition by v.branch order by (x ->> 'kpi')::int desc) rk
          from public.emp_view v, jsonb_array_elements(v.data -> v_mk) x
         where v.emp_id like '\_lb/%' and jsonb_typeof(v.data -> v_mk) = 'array')
      select cur.*, s.kpi old_kpi, s.rank old_rank from cur left join public.notif_kpi_snap s
        on s.branch = cur.branch and s.emp_id = cur.emp and s.mk = v_mk
    loop
      if r.old_kpi is not null and abs(r.kpi - r.old_kpi) >= 10 then
        perform public._notify_emp(r.emp, r.branch, 'kpi', case when r.kpi > r.old_kpi then '📈 تحسّن كبير في أدائك' else '📉 انخفاض في أدائك' end,
          'درجة KPI أصبحت ' || r.kpi || ' بعد أن كانت ' || r.old_kpi || ' الأسبوع الماضي', '?p=myperformance', 'kpi:' || v_sat);
      elsif r.old_rank is not null and r.rk <= 3 and r.old_rank > 3 then
        perform public._notify_emp(r.emp, r.branch, 'kpi', '🏆 دخلت أفضل 3!', 'ترتيبك الآن ' || r.rk || ' في الفرع — استمر', '?p=leaderboard', 'kpi:' || v_sat);
      elsif r.old_rank is not null and r.rk > 3 and r.old_rank <= 3 then
        perform public._notify_emp(r.emp, r.branch, 'kpi', 'خرجت من أفضل 3', 'ترتيبك الآن ' || r.rk || ' — تقدر ترجع بسهولة 💪', '?p=leaderboard', 'kpi:' || v_sat);
      end if;
      insert into public.notif_kpi_snap (branch, emp_id, mk, kpi, rank, at) values (r.branch, r.emp, v_mk, r.kpi, r.rk, now())
      on conflict (branch, emp_id, mk) do update set kpi = excluded.kpi, rank = excluded.rank, at = now();
    end loop;
  end if;
end $$;

-- every minute: reminders, the 09:00 daily jobs (once a day), then wake the sender if something is waiting
create or replace function public.notif_tick() returns void language plpgsql security definer set search_path to 'public' as $$
declare v_today text := public._cairo_now()::date::text;
begin
  perform public._notif_checkin_nudges();
  if extract(hour from public._cairo_now()) >= 9
     and coalesce((select v from public.notif_private where k = 'daily_done'), '') <> v_today then
    insert into public.notif_private (k, v) values ('daily_done', v_today) on conflict (k) do update set v = excluded.v;
    perform public._notif_daily();
  end if;
  if exists (select 1 from public.notifications where push_sent_at is null and send_after <= now())
     or not exists (select 1 from public.notif_private where k = 'vapid_public')
     or exists (select 1 from public.tg_links where used_at is null and created_at > now() - interval '15 minutes')
     -- Telegram bot not known yet (token just added): wake the sender every 5 minutes so it can set itself up
     or (not exists (select 1 from public.notif_private where k = 'tg_bot') and extract(minute from now())::int % 5 = 0) then
    perform net.http_post(
      url     := 'https://hxckdhdwafdxjntuohlw.supabase.co/functions/v1/notify-dispatch',
      headers := jsonb_build_object('Content-Type', 'application/json',
                                    'x-cron-secret', (select v from public.notif_private where k = 'cron_secret')),
      body    := '{}'::jsonb);
  end if;
end $$;

-- functions: internal ones closed, app ones for signed-in users only
do $$ declare fn text; begin
  for fn in select p.oid::regprocedure::text from pg_proc p join pg_namespace n on n.oid = p.pronamespace
            where n.nspname = 'public' and (p.proname like '\_notif%' or p.proname like '\_notify%'
                  or p.proname in ('_emp_active_in', 'notif_tick')) loop
    execute format('revoke all on function %s from public, anon, authenticated', fn);
  end loop;
  for fn in select p.oid::regprocedure::text from pg_proc p join pg_namespace n on n.oid = p.pronamespace
            where n.nspname = 'public' and p.proname in ('notify_emp', 'push_subscribe', 'push_unsubscribe', 'push_public_key', 'notif_mark_read') loop
    execute format('revoke all on function %s from public, anon', fn);
    execute format('grant execute on function %s to authenticated', fn);
  end loop;
end $$;

